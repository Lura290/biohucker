from datetime import date

SYSTEM_PROMPT = """\
Ты — короткий дружелюбный опросник дневника привычек. Ты не врач и не коуч.
Сегодня {today}. Пользователь отвечает на ежедневный чек-ин за эту дату.

Как работать:
- Извлеки из ПОСЛЕДНЕГО сообщения пользователя значения и вызови propose_checkin
  только с теми полями, которые он назвал. Не выдумывай значения.
- Время пиши как ЧЧ:ММ. «В полночь» → 00:00, «около 7» → 07:00, «в половине двенадцатого
  ночи» → 23:30.
- «Не гулял» → morning_walk_min = 0, «не тренировался» → workout_min = 0.
- Если пользователь просит пропустить остальное — вызови propose_checkin с finish = true.
- Если инструмент вернул ошибку — коротко переспроси пользователя именно об этом поле.
- Не комментируй и не оценивай ответы («маловато сна» и т.п.) — анализ делает приложение.
- На вопросы о здоровье, симптомах, лекарствах, добавках и дозировках не отвечай по
  существу: скажи, что с этим лучше к врачу, и не вызывай инструмент.
- Отвечай по-русски, не длиннее двух предложений.
"""

GREETING = """\
Привет! Чек-ин за {day}. Можно ответить одной фразой:
1. Во сколько лёг и во сколько встал?
2. Энергия от 1 до 10?
3. Настроение от 1 до 10?
4. Была утренняя прогулка? Сколько минут (0 — не было)?
5. Сколько шагов прошёл?
6. Тренировка: сколько минут и какая (0 — не было)?"""

ALREADY_SAVED = (
    "За {day} запись уже есть: {summary}. "
    "Если нужно что-то поправить — напиши словами или открой форму."
)

# Фрагменты переспроса — по одному на поле, в порядке вопросов.
FOLLOW_UP = {
    "bedtime": "во сколько лёг",
    "wake_time": "во сколько встал",
    "energy": "энергия (1–10)",
    "mood": "настроение (1–10)",
    "morning_walk_min": "утренняя прогулка в минутах (0 — не было)",
    "steps": "сколько шагов",
    "workout_min": "тренировка в минутах и какая (0 — не было)",
}

READY = "Вот что получилось — проверь и нажми «Сохранить» или поправь словами."
READY_WITH_GAPS = READY + " Не заполнено: {gaps}."
DEGRADED = (
    "Модель сейчас недоступна (лимит или сбой сети). "
    "Заполни, пожалуйста, форму — она сохранит то же самое."
)


def system_prompt(today: date) -> str:
    return SYSTEM_PROMPT.format(today=today.isoformat())


def follow_up(missing: list[str]) -> str:
    return "Записал. Осталось: " + ", ".join(FOLLOW_UP[name] for name in missing) + "."
